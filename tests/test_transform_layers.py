def toy(tmp_path: Path, contract: str = RICH) -> Any:
    return load_registry(write_registry(tmp_path / "reg", contract=contract)).get("toy_cases")


def test_intermediate_adds_one_column_per_contract_rule_and_changes_nothing(tmp_path: Path) -> None:
    ds = toy(tmp_path)
    cols = tg.derived_columns(ds.contract)
    assert [(n, t) for n, t, _s, _d in cols] == [
        ("is_total_row", "boolean"),
        ("reporting_area_label", "varchar"),
        ("reporting_area_partial_note", "varchar"),
        ("cases_flag_meaning", "varchar"),
    ]
    sql = tg.intermediate_sql(ds)
    assert sql.startswith("-- Generated by `make contracts` from contracts/toy_cases.odcs.yaml.")
    assert "from {{ ref('stg_toy_cases') }} as stg" in sql
    con = duckdb.connect()
    con.execute(
        "CREATE TABLE stg AS SELECT * FROM (VALUES "
        "('US RESIDENTS', 2023, 'L', 5, NULL, 1.0), ('new york', 2023, 'L', NULL, '-', NULL), "
        "('Commonwealth of Northern Mariana Islands', 2025, 'L', 1, 'Q', NULL), "
        "('Northern Mariana Islands', 2024, 'L', 2, NULL, NULL), (NULL, 2024, 'L', 2, NULL, NULL)) "
        "t(reporting_area, year, condition, cases, cases_flag, rate_per_100k)"
    )
    body = sql.split("\n", 3)[3].replace("{{ ref('stg_toy_cases') }}", "stg")
    rows = con.execute(body + " ORDER BY year, reporting_area NULLS LAST").fetchall()
    assert [r[-4:] for r in rows] == [
        (True, "US RESIDENTS", None, None),
        (False, "new york", "excludes New York City", "no reported cases"),
        (False, "Northern Mariana Islands", None, None),
        (False, None, None, None),
        (False, "Northern Mariana Islands", None, None),
    ]
    assert rows[1][:6] == (
        "new york",
        2023,
        "L",
        None,
        "-",
        None,
    )  # published values pass through as they are


def test_intermediate_handles_no_total_rows_star_places_and_name_clashes(tmp_path: Path) -> None:
    star = CONTRACT.replace("{property: totalRows, value: \"reporting_area = 'US RESIDENTS'\"}",
                            "{property: totalRows, value: none}").replace(
        "        customProperties: [{property: role, value: dimension}, {property: sourceField, value: states}]\n",
        "        customProperties: [{property: role, value: dimension}, {property: sourceField, value: states},"
        " {property: partialPlaces, value: {'*': every area is part of a state}}]\n", 1)  # fmt: skip
    cols = {n: (s, d) for n, _t, s, d in tg.derived_columns(toy(tmp_path, star).contract)}
    assert cols["is_total_row"][0] == "false" and cols["is_total_row"][1].startswith("Always false")
    assert cols["reporting_area_partial_note"][0] == (
        "CASE WHEN \"reporting_area\" IS NULL THEN NULL ELSE 'every area is part of a state' END"
    )
    clash = RICH.replace(
        "      - name: rate_per_100k\n",
        "      - name: cases_flag_meaning\n"
        "        physicalType: VARCHAR\n"
        "        logicalType: string\n"
        "        description: A column whose name staging would also derive.\n"
        "        customProperties: [{property: role, value: attribute}]\n"
        "      - name: rate_per_100k\n",
        1,
    )
    with pytest.raises(
        ValueError, match="toy_cases: the contract already has a column named cases_flag_meaning"
    ):
        tg.derived_columns(toy(tmp_path / "c", clash).contract)


def test_every_contract_rule_becomes_a_named_dbt_test_with_its_dimension_and_severity(tmp_path: Path) -> None:
    ds = toy(tmp_path)
    tests = [t["odcs_check"] for t in tg.quality_tests(ds)]
    assert [t["name"] for t in tests] == [f"toy_cases_{r.id}" for r in rules_for(ds.contract)]
    codes = tests[0]
    assert codes["config"] == {"severity": "error", "meta": {"dimension": "conformity", "rule": "flag_codes",
                               "contract": "contracts/toy_cases.odcs.yaml", "checks": "Codes from the codebook."}}  # fmt: skip
    assert codes["arguments"]["condition"] == "measured = 0"
    assert "{object}" in codes["arguments"]["measure_sql"]
    fill = next(t for t in tests if t["name"] == "toy_cases_fill_rate_cases")
    assert fill["config"]["severity"] == "warn" and fill["arguments"]["condition"] == "measured < 1.0"
    doc = yaml.safe_load(tg.intermediate_yml(ds))
    (m,) = doc["models"]
    assert m["name"] == "int_toy_cases" and m["config"]["contract"] == {"enforced": True}
    assert [c["name"] for c in m["columns"]][-4:] == [n for n, *_ in tg.derived_columns(ds.contract)]
    assert all("data_tests" not in c for c in m["columns"])  # code tests live on staging; rules on the model
    assert len(m["data_tests"]) == len(tests)


def test_the_dbt_test_and_the_read_path_agree(tmp_path: Path) -> None:
    """The macro's query (odcs_check.sql) over the same table gives a row exactly when run_rules says fail."""
    ds = toy(tmp_path)
    con = duckdb.connect()
    con.execute("CREATE TABLE t AS SELECT * FROM (VALUES ('A', 1, 'L', 3, 'X', 1.0), ('B', 1, 'L', NULL, '-', 2.0)) "
                "x(reporting_area, year, condition, cases, cases_flag, rate_per_100k)")  # fmt: skip
    results = {r["test"]: r["status"] for r in run_rules(con, "t", rules_for(ds.contract)).results}
    for rule in rules_for(ds.contract):
        sql = f"select measured from ({measure_sql(rule, 't')}) as m(measured) where not coalesce({condition_sql(rule, 'measured')}, false)"
        failed = bool(con.execute(sql).fetchall())
        assert failed == (results[rule.id] != "pass"), rule.id
    assert results["flag_codes"] == "fail"
    macro = (REPO / "transform" / "macros" / "odcs_check.sql").read_text()
    assert "{{ measure_sql | replace('{object}', model) }}" in macro and "{{ condition }}" in macro


@pytest.mark.parametrize(
    ("comparator", "bound", "sql"),
    [("mustBe", 0, "v = 0"), ("mustNotBe", "x", "v <> 'x'"), ("mustBeGreaterThan", 0, "v > 0"),
     ("mustBeGreaterOrEqualTo", 1, "v >= 1"), ("mustBeLessThan", 1.0, "v < 1.0"), ("mustBeLessOrEqualTo", 2, "v <= 2"),
     ("mustBeBetween", [21, 21], "v BETWEEN 21 AND 21"), ("mustNotBeBetween", [1, 2], "v NOT BETWEEN 1 AND 2")],
)  # fmt: skip
def test_condition_sql(comparator: str, bound: Any, sql: str) -> None:
    from health_data_registry.quality import Rule

    assert (
        condition_sql(
            Rule("r", "library", "d", "coverage", "error", comparator, bound, metric="rowCount"), "v"
        )
        == sql
    )


def test_unmapped_labels_lists_labels_missing_from_the_catalog(tmp_path: Path) -> None:
    catalog = CATALOG.replace(
        "status: draft\n",
        "status: draft\nconditions:\n  dimension: condition\n  source: toy codebook\n  labels: [Legionellosis, Syphilis]\n",
    )
    root = write_registry(tmp_path / "reg", catalog=catalog)
    sql = tg.unmapped_labels_sql(load_registry(root))
    assert "from {{ ref('int_toy_cases') }}" in sql and "not in ('Legionellosis', 'Syphilis')" in sql
    con = duckdb.connect()
    con.execute("CREATE TABLE i AS SELECT * FROM (VALUES ('Legionellosis'), ('Lyme disease'), ('Lyme disease'), (NULL)) "
                "t(condition)")  # fmt: skip
    rows = con.execute(sql.split("\n", 2)[2].replace("{{ ref('int_toy_cases') }}", "i")).fetchall()
    assert [r[:3] for r in rows] == [("toy_cases", "Lyme disease", 2)]
    assert "does not have this label" in rows[0][3]
    empty = tg.unmapped_labels_sql(load_registry(write_registry(tmp_path / "none")))
    assert duckdb.connect().execute(empty.split("\n", 2)[2]).fetchall() == []


