def test_intermediate_adds_one_column_per_contract_rule_and_changes_nothing(tmp_path: Path) -> None:
    ds = toy(tmp_path)
    cols = tg.derived_columns(ds.contract)
    assert [(n, t) for n, t, _s, _d in cols] == [
        ("is_total_row", "boolean"),
        ("reporting_area_key", "varchar"),
        ("reporting_area_label", "varchar"),
        ("reporting_area_partial_note", "varchar"),
        ("cases_flag_meaning", "varchar"),
    ]
    sql = tg.intermediate_sql(ds)
    assert sql.startswith("-- Generated by `make contracts` from contracts/toy_cases.odcs.yaml.")
    assert "from {{ ref('stg_toy_cases') }} as stg" in sql
    con = duckdb.connect()
    con.execute(
        "CREATE TABLE stg AS SELECT * FROM (VALUES "
        "('US RESIDENTS', 2023, 'L', 5, NULL, 1.0), ('new york', 2023, 'L', NULL, '-', NULL), "
        "('Commonwealth of Northern Mariana Islands', 2025, 'L', 1, 'Q', NULL), "
        "('Northern Mariana Islands', 2024, 'L', 2, NULL, NULL), (NULL, 2024, 'L', 2, NULL, NULL)) "
        "t(reporting_area, year, condition, cases, cases_flag, rate_per_100k)"
    )
    body = sql.split("\n", 3)[3].replace("{{ ref('stg_toy_cases') }}", "stg")
    rows = con.execute(body + " ORDER BY year, reporting_area NULLS LAST").fetchall()
    assert [r[-5:] for r in rows] == [
        (True, "US RESIDENTS", "US RESIDENTS", None, None),
        (False, "NEW YORK", "new york", "excludes New York City", "no reported cases"),
        (False, "NORTHERN MARIANA ISLANDS", "Northern Mariana Islands", None, None),
        (False, None, None, None, None),
        (False, "NORTHERN MARIANA ISLANDS", "Northern Mariana Islands", None, None),
    ]
    assert rows[1][:6] == (
        "new york",
        2023,
        "L",
        None,
        "-",
        None,
    )  # published values pass through as they are


