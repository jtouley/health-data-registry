def test_unmapped_labels_lists_labels_missing_from_the_catalog(tmp_path: Path) -> None:
    catalog = CATALOG.replace(
        "status: draft\n",
        "status: draft\nconditions:\n  dimension: condition\n  source: toy codebook\n  labels: [Legionellosis, Syphilis]\n",
    )
    root = write_registry(tmp_path / "reg", catalog=catalog)
    sql = tg.unmapped_labels_sql(load_registry(root))
    assert "from {{ ref('int_toy_cases') }}" in sql and "not in ('Legionellosis', 'Syphilis')" in sql
    con = duckdb.connect()
    con.execute("CREATE TABLE i AS SELECT * FROM (VALUES ('Legionellosis'), ('Lyme disease'), ('Lyme disease'), (NULL)) "
                "t(condition)")  # fmt: skip
    rows = con.execute(sql.split("\n", 2)[2].replace("{{ ref('int_toy_cases') }}", "i")).fetchall()
    assert [r[:3] for r in rows] == [("toy_cases", "Lyme disease", 2)]
    assert "does not have this label" in rows[0][3]
    empty = tg.unmapped_labels_sql(load_registry(write_registry(tmp_path / "none")))
    assert duckdb.connect().execute(empty.split("\n", 2)[2]).fetchall() == []


