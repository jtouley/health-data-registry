"""Generate the dbt project's raw sources, staging models and model schemas from contracts/ (`make contracts`).

Nothing in transform/models/staging/ is written by hand. For each catalogued source this writes:

    transform/models/staging/_raw_sources.yml   the versioned raw contract of every stored source: the
                                                publisher fields the fetcher hands on, all text, with the
                                                contract version. Changing a field without bumping the contract
                                                version is refused here, so a fetcher can't change a column
                                                quietly. The dbt_raw plugin resolves each source to the one load
                                                the dataset's LATEST pointer names.
    transform/models/staging/stg_<id>.sql       the typed projection (staging.typed_select, the same one the lake
                                                and the live read use) over that load, with each row's snapshot id
                                                and raw sha256. No row is dropped or deduplicated.
    transform/models/staging/stg_<id>.yml       an enforced dbt model contract: each column's data type, its
                                                description in clinical words, its meta (logical type, source
                                                field, unit, codes, missing codes), not_null for required
                                                columns, a fill-rate test for every other column the contract
                                                doesn't mark mayBeEmpty, the flag code list as an accepted_values
                                                test, and a one-row-per-key test when the contract declares a key

For each contract in contracts/models/ (a model computed in dbt, such as the MMWR calendar) it writes
transform/models/<layer>/<id>.yml (layer: reference, intermediate or marts), the same enforced dbt contract; the
model's SQL is hand-written beside it, except for four models whose rows come from the registry itself:

    marts/dim_place.sql                     the place list in dim_place's contract (the one definition geo.py
                                            reads too), and the counties the Census file lists
    reference/coverage_declarations.sql     every contract's coverage block, one row per declared place and interval
    intermediate/int_observed_places.sql    the places and years each stored source's rows name (coverage.observed)
    flag/flag_unmapped_labels.sql           labels missing from each source's catalog list
So every column of every model has its type, description and constraints from an ODCS contract, and dbt has
no seeds and no data files (owner decision, 25 Nov).

Sources read live only (licence.redistribution: false, e.g. WHO GHO) get no dbt model: they are never stored
(ADR 0009), so there is nothing on disk for dbt to read. Their in-memory staging uses the same projection.

`make contracts` writes the files; `check` (and tests/test_transform_gen.py in CI) fails when the committed
files differ from what the contracts generate. It deletes only files it generated (they start with the generated
header) in staging/, and refuses, naming them, rather than delete or overwrite anything else: hand-written
intermediate, flag and mart models and their schemas are never touched.
"""

