"""Generate the dbt project's raw sources, staging models and model schemas from contracts/ (`make contracts`).

Nothing in transform/models/staging/ is written by hand. For each catalogued source this writes:

    transform/models/staging/_raw_sources.yml   the versioned raw contract of every stored source: the
                                                publisher fields the fetcher hands on, all text, with the
                                                contract version. Changing a field without bumping the contract
                                                version is refused here, so a fetcher can't change a column
                                                quietly. The dbt_raw plugin resolves each source to the one load
                                                the dataset's LATEST pointer names.
    transform/models/staging/stg_<id>.sql       the typed projection (staging.typed_select, the same one the lake
                                                and the live read use) over that load, with each row's snapshot id
                                                and raw sha256. No row is dropped or deduplicated.
    transform/models/staging/stg_<id>.yml       an enforced dbt model contract: each column's data type, its
                                                description in clinical words, its meta (logical type, source
                                                field, unit, codes, missing codes), not_null for required
                                                columns, a fill-rate test for every other column the contract
                                                doesn't mark mayBeEmpty, the flag code list as an accepted_values
                                                test, and a one-row-per-key test when the contract declares a key

For each contract in contracts/models/ (a model computed in dbt, such as the MMWR calendar) it writes
transform/models/<layer>/<id>.yml (layer: reference, intermediate or marts), the same enforced dbt contract; the
model's SQL is hand-written beside it.
So every column of every model has its type, description and constraints from an ODCS contract, and dbt has
no seeds and no data files (owner decision, 25 Nov).

Sources read live only (licence.redistribution: false, e.g. WHO GHO) get no dbt model: they are never stored
(ADR 0009), so there is nothing on disk for dbt to read. Their in-memory staging uses the same projection.

`make contracts` writes the files; `check` (and tests/test_transform_gen.py in CI) fails when the committed
files differ from what the contracts generate. It deletes only files it generated (they start with the generated
header) in staging/, and refuses, naming them, rather than delete or overwrite anything else: hand-written
intermediate, flag and mart models and their schemas are never touched.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

from health_data_registry.dbt_raw import PROVENANCE, SHA256_COLUMN, SNAPSHOT_COLUMN
from health_data_registry.registry import Contract, Dataset, Registry, load_registry, parse_contract
from health_data_registry.staging import raw_fields, silver_schema, staged_source, typed_select

MODELS_DIR = Path("transform/models")
STAGING_DIR = MODELS_DIR / "staging"
SOURCES_FILE = STAGING_DIR / "_raw_sources.yml"
MODEL_CONTRACTS = Path("contracts/models")
GENERATED_MARK = "Generated by `make contracts`"
HEADER = GENERATED_MARK + " from {src}. Do not edit: change the contract and regenerate."
LAYERS = ("reference", "intermediate", "marts")
PROVENANCE_DOCS = {
    SNAPSHOT_COLUMN: "The lake snapshot this row was read from (the dataset's LATEST load). Its manifest gives the "
    "source address, retrieval time and dataset version that go with every answer built on this row.",
    SHA256_COLUMN: "The sha256 fingerprint of each raw file the row was parsed from, space-separated in fetch "
    "order: the exact bytes the publisher sent.",
}

# What the adapter itself adds to a row (never a publisher value; hard rule 15), described as what it is, so the
# raw source never calls it a publisher field.
ADDED_DOCS = {
    "document_url": "Added by the adapter: the address of the document this row was read from, with any access "
    "key removed.",
    "document_sha256": "Added by the adapter: the sha256 fingerprint of that document's raw bytes, as kept in the "
    "lake's raw store.",
    "document_retrieved_at": "Added by the adapter: when that document was fetched (ISO 8601, UTC).",
    "failed_checks": "Added by the adapter: each check of the table against its own printed totals that this row "
    "(or, in the long layout, this cell) failed, as a JSON array of plain sentences; [] when it failed none or none "
    "applied. No value is changed by a check.",
    "column_header": "Built by the adapter (long layout): the printed header of the column this cell sits in.",
    "cell_text": "Built by the adapter (long layout): the cell's text exactly as printed.",
}

DBT_TYPES = {
    "VARCHAR": "varchar",
    "BIGINT": "bigint",
    "INTEGER": "integer",
    "DOUBLE": "double",
    "DATE": "date",
    "TIMESTAMP": "timestamp",
    "BOOLEAN": "boolean",
}


class RawContractChanged(ValueError):
    """A source's raw fields changed while its contract version stayed the same."""


class NotGenerated(ValueError):
    """`make contracts` found files in its place that it didn't generate, and won't delete or overwrite them."""


def stored(registry: Registry) -> list[Dataset]:
    """The sources dbt reads: those whose licence lets them be stored."""
    return [ds for ds in registry if ds.entry.licence.redistribution]


def source_fields(contract: Contract) -> list[str]:
    return sorted({c.source_field for c in contract.columns})


def primary_key(contract: Contract) -> list[str]:
    """The contract's own primary key (ODCS primaryKey: true, in primaryKeyPosition order); empty if undeclared."""
    props = ((contract.raw.get("schema") or [{}])[0]).get("properties") or []
    keyed = [p for p in props if p.get("primaryKey") is True]
    return [str(p["name"]) for p in sorted(keyed, key=lambda p: int(p.get("primaryKeyPosition") or 0))]


def _dump(header: str, doc: Mapping[str, Any]) -> str:
    body = yaml.safe_dump(dict(doc), sort_keys=False, allow_unicode=True, width=110)
    return f"# {header}\n{body}"


def _staging_steps(ds: Dataset) -> list[tuple[Any, Any]]:
    from health_data_registry.adapters.extensions import resolved

    return resolved(ds.entry.source.extensions, "staging")


def _raw_description(ds: Dataset, f: str, read_into: Mapping[str, list[str]]) -> str:
    """What one raw field holds: the adapter's own metadata as such; a publisher field and the contract column it
    is read into, or, for a field a staging step reads, which value it holds and the column it lands in."""
    into = "; read into " + "; ".join(read_into[f]) if f in read_into else ""
    if f in ADDED_DOCS:
        return ADDED_DOCS[f] + into
    if into:
        return f"Publisher field {f}, as text{into}"
    for ext, args in _staging_steps(ds):
        explained = ext.explain_input(args, f) if ext.explain_input is not None else None
        if explained is not None:
            lands, what = explained
            column = "; ".join(read_into.get(lands, [])) or lands
            return f"Publisher field {f}, as text: {what} ({ext.name}), into {column}"
    names = ", ".join(ext.name for ext, _a in _staging_steps(ds))
    return f"Publisher field {f}, as text; read by staging ({names}) and kept as it is"


def raw_sources(registry: Registry) -> str:
    tables = []
    for ds in stored(registry):
        fields = raw_fields(ds.entry, source_fields(ds.contract))
        read_into: dict[str, list[str]] = {}
        for c in ds.contract.columns:
            read_into.setdefault(c.source_field, []).append(f"{c.name} ({c.description})")
        columns = [
            {"name": f, "data_type": "varchar", "description": _raw_description(ds, f, read_into)}
            for f in fields
        ]
        columns += [
            {"name": p, "data_type": "varchar", "description": PROVENANCE_DOCS[p]} for p in PROVENANCE
        ]
        steps = _staging_steps(ds)
        held = (
            "the file exactly as the publisher laid it out; staging reshapes it ("
            + ", ".join(ext.name for ext, _a in steps)
            + ")"
            if steps
            else "the publisher's own fields, or for a wide table the adapter's structural reshaping of them (see "
            "the staging model)"
        )
        tables.append(
            {
                "name": ds.id,
                "description": f"Raw records of {ds.entry.title} as the adapter hands them on, every value as "
                f"text: {held}. Only the full load the dataset's LATEST pointer names is read.",
                "meta": {
                    "raw_contract_version": ds.contract.version,
                    "contract": ds.entry.contract,
                    "plugin": "hdr_raw",
                    "source_fields": fields,
                },
                "columns": columns,
            }
        )
    doc = {
        "version": 2,
        "sources": [
            {
                "name": "raw",
                "description": "Parsed publisher records in the lake (raw_records/<id>/<snapshot id>.ndjson), "
                "resolved to the dataset's LATEST full load by the dbt_raw plugin (profiles.yml).",
                "schema": "raw",
                "tables": tables,
            }
        ],
    }
    return _dump(HEADER.format(src="contracts/"), doc)


def staging_sql(ds: Dataset) -> str:
    provenance = ",\n  ".join(f'"{p}"' for p in PROVENANCE)
    # The source's staging extensions (if any) wrap the raw relation: the same SQL the lake and the live read run.
    raw = f"{{{{ source('raw', '{ds.id}') }}}}"
    sql, _fields, rows_per_row = staged_source(ds.entry, raw, None)
    steps = _staging_steps(ds)
    reshape = (
        "-- Staging steps: "
        + ", ".join(ext.name for ext, _a in steps)
        + f" (one raw row makes {rows_per_row} rows; they reshape, never compute or filter). The load checks the\n"
        "-- file's layout and this row count before LATEST moves (staging.stage_entry); dbt reads only that load.\n"
        if steps
        else ""
    )
    return (
        f"-- {HEADER.format(src=ds.entry.contract)}\n"  # noqa: S608 - generated from quoted contract identifiers
        "-- Types the load the dataset's LATEST pointer names; every business rule lives in intermediate models.\n"
        f"{reshape}"
        "-- No row is dropped or deduplicated: a duplicate key fails the model's one-row-per-key test.\n"
        f"select\n  {typed_select(ds.contract)},\n  {provenance}\n"
        f"from {sql}\n"
    )


def _columns(contract: Contract, model: str, made: Mapping[str, str] | None = None) -> list[dict[str, Any]]:
    """The dbt columns of a model: every type, description, constraint and code list from its contract. ``made``
    names the staging step that makes a source field the publisher never sent (wide_to_long's key)."""
    columns = []
    for c in silver_schema(contract):
        column = contract.column(c.name)
        description = c.description
        if column.flag_codes:
            meanings = "; ".join(f"{code} = {meaning}" for code, meaning in column.flag_codes)
            description = f"{description} Codes (publisher's codebook): {meanings}."
        col: dict[str, Any] = {
            "name": c.name,
            "data_type": DBT_TYPES[c.physical_type],
            "description": description,
            "meta": {
                "logical_type": c.logical_type,
                "physical_type": c.physical_type,
                "source_field": c.source_field,
                "unit": c.unit,
                "codes": list(c.codes),
                "missing_codes": list(c.missing_codes),
            },
        }
        if made and c.source_field in made:
            col["meta"]["made_by"] = made[c.source_field]
        tests: list[dict[str, Any]] = []
        if column.required:
            col["constraints"] = [{"type": "not_null"}]
        elif not column.may_be_empty:
            # An all-empty column passes every value check: a renamed publisher field would load that way.
            # Warn here: the load itself refuses a declared field that never appears (staging.stage).
            tests.append(
                {"not_all_empty": {"name": f"{model}_{c.name}_filled", "config": {"severity": "warn"}}}
            )
        if c.codes:
            tests.append(
                {
                    "accepted_values": {
                        "name": f"{model}_{c.name}_codes",
                        "arguments": {"values": list(c.codes)},
                        "config": {"severity": "warn", "where": f"nullif(trim({c.name}), '') is not null"},
                    }
                }
            )
        if tests:
            col["data_tests"] = tests
        columns.append(col)
    return columns


def _model_yml(
    contract: Contract,
    model: str,
    contract_path: str,
    tags: list[str],
    *,
    provenance: bool = False,
    steps: list[dict[str, Any]] | None = None,
) -> str:
    schema = (contract.raw.get("schema") or [{}])[0]
    pk = primary_key(contract)
    description = str(schema.get("description") or contract.id).strip()
    if steps:
        grain = " and ".join(k for s in steps for k in s["adds_to_grain"])
        description = description if description.endswith(".") else description + "."
        description += (
            f" Staging reshapes the raw load ({', '.join(s['name'] for s in steps)}): one row per raw row"
            + (f" and {grain}" if grain else "")
            + "; no row is dropped."
        )
    entry: dict[str, Any] = {
        "name": model,
        "description": description,
        "config": {"materialized": "table", "contract": {"enforced": True}, "tags": tags},
        "meta": {
            "contract": contract_path,
            "contract_id": contract.id,
            "contract_version": contract.version,
            "contract_status": contract.status,
            "primary_key": pk,
        },
    }
    if steps:
        entry["meta"]["staging_extensions"] = steps
    if pk:
        # A test, not a dedupe: two rows with one key in a load are a data finding, never resolved in SQL.
        entry["data_tests"] = [
            {"one_row_per_key": {"name": f"{model}_one_row_per_{'_'.join(pk)}", "arguments": {"columns": pk}}}
        ]
    made = {k: s["name"] for s in steps or [] for k in s["adds_to_grain"]}
    entry["columns"] = _columns(contract, model, made)
    if provenance:
        entry["columns"] += [
            {
                "name": p,
                "data_type": "varchar",
                "description": PROVENANCE_DOCS[p],
                "constraints": [{"type": "not_null"}],
            }
            for p in PROVENANCE
        ]
    return _dump(HEADER.format(src=contract_path), {"version": 2, "models": [entry]})


def staging_yml(ds: Dataset) -> str:
    steps = []
    for ext, args in _staging_steps(ds):
        step = ext.run(args, "raw", list(ext.input_fields(args)))
        steps.append({"name": ext.name, "hook": "staging", "rows_per_row": step.rows_per_row,
                      "adds_to_grain": list(step.key_fields)})  # fmt: skip
    return _model_yml(
        ds.contract, f"stg_{ds.id}", ds.entry.contract, ["staging"], provenance=True, steps=steps or None
    )


def model_contracts(root: Path) -> list[tuple[Path, Contract]]:
    """The contracts of models computed in dbt (contracts/models/<id>.odcs.yaml), each parsed like a dataset's."""
    out = []
    for path in sorted((root / MODEL_CONTRACTS).glob("*.odcs.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        out.append(
            (path.relative_to(root), parse_contract(doc, expected_id=path.name.removesuffix(".odcs.yaml")))
        )
    return out


def model_layer(contract: Contract) -> str:
    schema = (contract.raw.get("schema") or [{}])[0]
    layers = [p.get("value") for p in schema.get("customProperties") or [] if p.get("property") == "layer"]
    if len(layers) != 1 or layers[0] not in LAYERS:
        raise ValueError(
            f"{contract.id}: a model contract declares its layer once, as one of {', '.join(LAYERS)}"
        )
    return str(layers[0])


def generate(registry: Registry) -> dict[Path, str]:
    """Every generated file, keyed by its path relative to the repo root."""
    out: dict[Path, str] = {SOURCES_FILE: raw_sources(registry)}
    for ds in stored(registry):
        out[STAGING_DIR / f"stg_{ds.id}.sql"] = staging_sql(ds)
        out[STAGING_DIR / f"stg_{ds.id}.yml"] = staging_yml(ds)
    for path, contract in model_contracts(registry.root):
        layer = model_layer(contract)
        out[MODELS_DIR / layer / f"{contract.id}.yml"] = _model_yml(contract, contract.id, str(path), [layer])
    return out


def _raw_versions(text: str) -> dict[str, tuple[str, list[str]]]:
    doc = yaml.safe_load(text) or {}
    found: dict[str, tuple[str, list[str]]] = {}
    for src in doc.get("sources") or []:
        for t in src.get("tables") or []:
            meta = t.get("meta") or {}
            found[str(t["name"])] = (
                str(meta.get("raw_contract_version", "")),
                [str(c["name"]) for c in t.get("columns") or [] if c["name"] not in PROVENANCE],
            )
    return found


def check_raw_versions(old: str, new: str) -> None:
    """Refuse a raw field change that keeps the same contract version."""
    before, after = _raw_versions(old), _raw_versions(new)
    for name, (version, fields) in after.items():
        if name in before and before[name][0] == version and before[name][1] != fields:
            raise RawContractChanged(
                f"{name}: the raw fields changed ({', '.join(before[name][1])} -> {', '.join(fields)}) but the "
                f"contract version is still {version}; bump the contract's version"
            )


def is_generated(path: Path) -> bool:
    """True when the file starts with the generated header (a # or -- comment)."""
    try:
        with path.open(encoding="utf-8") as fh:
            first = fh.readline()
    except (OSError, UnicodeDecodeError):
        return False
    return first.startswith(("# ", "-- ")) and GENERATED_MARK in first


def strays(root: Path, files: Mapping[Path, str]) -> list[Path]:
    """Files the generator doesn't write now: anything in staging/, and generated files elsewhere."""
    found = []
    models = root / MODELS_DIR
    if models.is_dir():
        for p in sorted(models.rglob("*")):
            rel = p.relative_to(root)
            if p.is_file() and rel not in files and (rel.parent == STAGING_DIR or is_generated(p)):
                found.append(rel)
    return found


def _differs(path: Path, text: str) -> bool:
    return not path.is_file() or path.read_text(encoding="utf-8") != text


def stale(root: Path, files: Mapping[Path, str]) -> list[str]:
    """Generated files that are missing or differ, and stray files in the generator's place."""
    out = [str(p) for p, text in files.items() if _differs(root / p, text)]
    return out + [str(p) for p in strays(root, files)]


def write(root: Path, files: Mapping[Path, str]) -> list[str]:
    """Write every generated file. Deletes only stale generated files in staging/; refuses on anything else."""
    old = root / SOURCES_FILE
    if old.is_file():
        check_raw_versions(old.read_text(encoding="utf-8"), files[SOURCES_FILE])
    kept = [p for p in files if (root / p).is_file() and not is_generated(root / p)]
    found = strays(root, files)
    deletable = [p for p in found if p.parent == STAGING_DIR and is_generated(root / p)]
    refused = sorted({*kept, *(p for p in found if p not in deletable)})
    if refused:
        raise NotGenerated(
            "make contracts writes and deletes only its own generated files, and these are in its place but "
            "weren't generated (or are generated files outside staging/ that no contract makes any more): "
            + ", ".join(str(p) for p in refused)
            + ". Move hand-written models out of staging/, or delete these files yourself, then run it again."
        )
    changed = stale(root, files)
    for p in deletable:
        (root / p).unlink()
    for path, text in files.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed files differ; write nothing")
    ap.add_argument("--root", type=Path, default=Path.cwd())
    args = ap.parse_args(argv)
    registry = load_registry(args.root)
    files = generate(registry)
    if args.check:
        committed = args.root / SOURCES_FILE
        if committed.is_file():
            check_raw_versions(committed.read_text(encoding="utf-8"), files[SOURCES_FILE])
        differ = stale(args.root, files)
        for p in differ:
            print(f"out of date: {p} (run make contracts)", file=sys.stderr)
        return 1 if differ else 0
    try:
        written = write(args.root, files)
    except (NotGenerated, RawContractChanged) as e:
        print(f"make contracts stopped: {e}", file=sys.stderr)
        return 1
    for p in written:
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
