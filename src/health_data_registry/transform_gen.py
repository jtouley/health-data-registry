def _sql_value(v: object, typ: str = "varchar") -> str:
    return (
        f"cast(null as {typ})"
        if v is None
        else _lit(str(v))
        if typ == "varchar"
        else f"cast({_lit(str(v))} as {typ})"
    )


def _values(columns: list[tuple[str, str]], rows: list[list[object]]) -> str:
    """A typed VALUES list: every value cast to its column's type, so an empty first value can't set the type."""
    names = ", ".join(n for n, _t in columns)
    body = ",\n    ".join(
        "(" + ", ".join(_sql_value(v, t) for v, (_n, t) in zip(row, columns, strict=True)) + ")"
        for row in rows
    )
    return f"(values\n    {body}\n) as t({names})"


def dim_place_sql(contract: Contract) -> str:
    """dim_place: the fixed places its contract lists (the one definition geo.py reads), then the Census counties."""
    places = next(
        cp["value"] for cp in contract.raw.get("customProperties") or [] if cp.get("property") == "places"
    )
    n = places["nation"]
    rows: list[list[object]] = [[n["key"], n["name"], "nation", None, None, n["fips"], n["postal"]]]
    for name, postal, fips in places["states"]:
        key = f"US-{fips}"
        rows.append([key, name, "state", geo.parent_key(key), geo.territory_of(key), fips, postal])
    rows += [
        [f"US-{f}", name, "state", geo.parent_key(f"US-{f}"), geo.territory_of(f"US-{f}"), f, postal]
        for name, postal, f in places["territories"]
    ]
    rows += [
        [c["key"], c["name"], "city", geo.parent_key(c["key"]), None, None, None] for c in places["cities"]
    ]
    rows += [[k, name, "country", None, None, None, None] for k, name in places["countries"]]
    rows += [[r["key"], r["name"], "who_region", None, None, None, None] for r in places["whoRegions"]]
    names = ("place_key", "place_name", "place_level", "parent_key", "territory_of", "fips", "postal")
    cols = [(c, "varchar") for c in names]
    return (
        f"-- {HEADER.format(src=str(MODEL_CONTRACTS / 'dim_place.odcs.yaml'))}\n"
        "-- The fixed places come from the contract's places list, the same list geo.py reads; counties come from the\n"
        "-- Census county population file (SUMLEV 050 rows), named as in its latest year. No data file is read.\n"
        f"select * from {_values(cols, rows)}\n"
        "union all\n"
        "select\n"
        "    'US-' || state_fips || county_fips as place_key,\n"
        "    arg_max(county_name, year) as place_name,\n"
        "    'county' as place_level,\n"
        "    'US-' || state_fips as parent_key,\n"
        "    cast(null as varchar) as territory_of,\n"
        "    state_fips || county_fips as fips,\n"
        "    cast(null as varchar) as postal\n"
        f"from {{{{ ref('int_{CENSUS}') }}}}\n"
        "where sumlev = '050' and state_fips is not null and county_fips is not null\n"
        "group by state_fips, county_fips\n"
    )


def coverage_declarations_sql(registry: Registry) -> str:
    """Every contract's coverage block as rows: the input of dim_dataset_coverage (no seed, no data file)."""
    cols = [("dataset_id", "varchar"), ("place_key", "varchar"), ("valid_from", "bigint"), ("valid_to", "bigint"),
            ("coverage_kind", "varchar"), ("denominator", "varchar"), ("time_unit", "varchar"), ("part", "varchar"),
            ("counties", "varchar"), ("basis_url", "varchar"), ("basis_quote", "varchar"),
            ("contract_version", "varchar"), ("declared_in_contract_version", "varchar"), ("declared_at", "date"),
            ("dataset_first_year", "bigint"), ("dataset_last_year", "bigint"), ("reported_levels", "varchar"),
            ("national_scope", "varchar")]  # fmt: skip
    rows: list[list[object]] = []
    for ds in registry:
        cov = ds.contract.coverage
        if cov is None:
            continue
        e = ds.entry
        common = [cov.kind, cov.denominator, cov.time_unit]
        tail = [e.years.start, e.years.end, " ".join(e.geography),
                cov.national_scope.includes if cov.national_scope else None]  # fmt: skip
        if not cov.places:
            rows.append([ds.id, None, None, None, *common, None, None, None, None, ds.contract.version, None, None,
                         *tail])  # fmt: skip
        for pl in cov.places:
            rows.append([ds.id, pl.place_key, pl.valid_from, pl.valid_to, *common, pl.part,
                         " ".join(pl.counties) if pl.counties else None, pl.basis_url, pl.basis_quote,
                         ds.contract.version, pl.declared_in_version, pl.declared_at, *tail])  # fmt: skip
    # Each SQL line is its own list item, built only from quoted literals (_lit) and fixed names.
    empty = ", ".join(f"cast(null as {t}) as {n}" for n, t in cols)
    body = "\n".join(
        ["select *", f"from {_values(cols, rows)}", ""] if rows else [f"select {empty}", "where false", ""]
    )
    return (
        f"-- {HEADER.format(src='contracts/ (customProperties.coverage)')}\n"
        "-- One row per declared place and interval; a source that declares no place has one row with no place.\n"
        + body
    )


def observed_places_sql(registry: Registry) -> str:
    """The places and years each stored source's rows name, keyed to dim_place by its conformedDimensions."""
    parts = []
    for ds in stored(registry):
        cd = ds.contract.conformed
        if cd is None or cd.year_column is None or cd.match not in ("state_name", "fips"):
            continue
        year = _q(cd.year_column)
        if cd.match == "fips":
            state = f"src.{_q(cd.state_column or '')}"
            county = f"src.{_q(cd.county_column)}" if cd.county_column else None
            tail = f" || CASE WHEN {county} = '000' THEN '' ELSE {county} END" if county else ""
            key, join, where = f"'US-' || {state}{tail}", "", f"{state} IS NOT NULL"
        else:
            levels = ", ".join(_lit(x) for x in ds.entry.geography)
            labels = "".join(
                f"\n        union select {_lit(label_key(c.label))}, {_lit(c.key)}"
                for c in cd.places
                if c.label is not None and c.key is not None
            )
            join = "\n".join(
                [
                    "",
                    "join (",
                    f"        select {label_key_sql('place_name')} as label_key, place_key",
                    "        from {{ ref('dim_place') }}",
                    f"        where place_level in ({levels}){labels}",
                    f"    ) as k on {_key_sql_src(cd.column or '')} = k.label_key",
                ]
            )
            key, where = "k.place_key", f"src.{_q(cd.column or '')} IS NOT NULL"
        parts.append(
            "\n".join(
                [
                    f"select {_lit(ds.id)} as dataset_id, {key} as place_key, cast(src.{year} as bigint) as year,",
                    "    count(*) as row_count",
                    f"from {{{{ ref('int_{ds.id}') }}}} as src{join}",
                    f"where {where} and src.{year} IS NOT NULL",
                    "group by all",
                ]
            )
        )
    body = "\nunion all\n".join(parts) or (
        "select cast(null as varchar) as dataset_id, cast(null as varchar) as place_key, "
        "cast(null as bigint) as year, cast(0 as bigint) as row_count where false"
    )
    return (
        f"-- {HEADER.format(src='contracts/ (schema customProperties.conformedDimensions)')}\n"
        "-- A place label matches dim_place by name (label_key: case, edge spaces and dots ignored) at the levels the\n"
        "-- source reports, or by its contract's conformedDimensions label; FIPS sources build the key (county 000 is\n"
        "-- the Census file's state row). A label that names no place in dim_place is left out.\n"
        f"{body}\n"
    )


def _key_sql_src(col: str) -> str:
    return label_key_sql(f"src.{_q(col)}")


def intermediate_yml(ds: Dataset) -> str:
    schema = (ds.contract.raw.get("schema") or [{}])[0]
    columns = [
        # A view takes no constraints (dbt-duckdb): the staging table under it enforces them.
        {k: v for k, v in c.items() if k not in ("data_tests", "constraints")}
        for c in _columns(ds.contract, f"int_{ds.id}")
    ]
    # Every row keeps the snapshot id and raw sha256 staging carries (hard rule 8).
    columns += [{"name": p, "data_type": "varchar", "description": PROVENANCE_DOCS[p]} for p in PROVENANCE]
    columns += [
        {"name": name, "data_type": typ, "description": desc, "meta": {"derived_from_contract": True}}
        for name, typ, _sql, desc in derived_columns(ds.contract)
    ]
    entry = {
        "name": f"int_{ds.id}",
        "description": str(schema.get("description") or ds.entry.title).strip(),
        "config": {"materialized": "view", "contract": {"enforced": True}, "tags": ["intermediate"]},
        "meta": {
            "contract": ds.entry.contract,
            "contract_id": ds.contract.id,
            "contract_version": ds.contract.version,
            "contract_status": ds.contract.status,
        },
        "data_tests": quality_tests(ds),
        "columns": columns,
    }
    return _dump(HEADER.format(src=ds.entry.contract), {"version": 2, "models": [entry]})


def generate(registry: Registry) -> dict[Path, str]:
    """Every generated file, keyed by its path relative to the repo root."""
    out: dict[Path, str] = {SOURCES_FILE: raw_sources(registry)}
    for ds in stored(registry):
        out[STAGING_DIR / f"stg_{ds.id}.sql"] = staging_sql(ds)
        out[STAGING_DIR / f"stg_{ds.id}.yml"] = staging_yml(ds)
        out[INTERMEDIATE_DIR / f"int_{ds.id}.sql"] = intermediate_sql(ds)
        out[INTERMEDIATE_DIR / f"int_{ds.id}.yml"] = intermediate_yml(ds)
    out[UNMAPPED_LABELS] = unmapped_labels_sql(registry)
    for path, contract in model_contracts(registry.root):
        layer = model_layer(contract)
        out[MODELS_DIR / layer / f"{contract.id}.yml"] = _model_yml(contract, contract.id, str(path), [layer])
        if contract.id == "dim_place":
            out[MODELS_DIR / layer / "dim_place.sql"] = dim_place_sql(contract)
        elif contract.id == "coverage_declarations":
            out[MODELS_DIR / layer / "coverage_declarations.sql"] = coverage_declarations_sql(registry)
        elif contract.id == "int_observed_places":
            out[MODELS_DIR / layer / "int_observed_places.sql"] = observed_places_sql(registry)
    return out


def _raw_versions(text: str) -> dict[str, tuple[str, list[str]]]:
    doc = yaml.safe_load(text) or {}
    found: dict[str, tuple[str, list[str]]] = {}
    for src in doc.get("sources") or []:
        for t in src.get("tables") or []:
            meta = t.get("meta") or {}
            found[str(t["name"])] = (
                str(meta.get("raw_contract_version", "")),
                [str(c["name"]) for c in t.get("columns") or [] if c["name"] not in PROVENANCE],
            )
    return found


def check_raw_versions(old: str, new: str) -> None:
    """Refuse a raw field change that keeps the same contract version."""
    before, after = _raw_versions(old), _raw_versions(new)
    for name, (version, fields) in after.items():
        if name in before and before[name][0] == version and before[name][1] != fields:
            raise RawContractChanged(
                f"{name}: the raw fields changed ({', '.join(before[name][1])} -> {', '.join(fields)}) but the "
                f"contract version is still {version}; bump the contract's version"
            )


def is_generated(path: Path) -> bool:
    """True when the file starts with the generated header (a # or -- comment)."""
    try:
        with path.open(encoding="utf-8") as fh:
            first = fh.readline()
    except (OSError, UnicodeDecodeError):
        return False
    return first.startswith(("# ", "-- ")) and GENERATED_MARK in first


def strays(root: Path, files: Mapping[Path, str]) -> list[Path]:
    """Files the generator doesn't write now: anything in staging/, and generated files elsewhere."""
    found = []
    models = root / MODELS_DIR
    if models.is_dir():
        for p in sorted(models.rglob("*")):
            rel = p.relative_to(root)
            if p.is_file() and rel not in files and (rel.parent == STAGING_DIR or is_generated(p)):
                found.append(rel)
    return found


def _differs(path: Path, text: str) -> bool:
    return not path.is_file() or path.read_text(encoding="utf-8") != text


def stale(root: Path, files: Mapping[Path, str]) -> list[str]:
    """Generated files that are missing or differ, and stray files in the generator's place."""
    out = [str(p) for p, text in files.items() if _differs(root / p, text)]
    return out + [str(p) for p in strays(root, files)]


def write(root: Path, files: Mapping[Path, str]) -> list[str]:
    """Write every generated file. Deletes only stale generated files in staging/; refuses on anything else."""
    old = root / SOURCES_FILE
    if old.is_file():
        check_raw_versions(old.read_text(encoding="utf-8"), files[SOURCES_FILE])
    kept = [p for p in files if (root / p).is_file() and not is_generated(root / p)]
    found = strays(root, files)
    deletable = [p for p in found if p.parent == STAGING_DIR and is_generated(root / p)]
    refused = sorted({*kept, *(p for p in found if p not in deletable)})
    if refused:
        raise NotGenerated(
            "make contracts writes and deletes only its own generated files, and these are in its place but "
            "weren't generated (or are generated files outside staging/ that no contract makes any more): "
            + ", ".join(str(p) for p in refused)
            + ". Move hand-written models out of staging/, or delete these files yourself, then run it again."
        )
    changed = stale(root, files)
    for p in deletable:
        (root / p).unlink()
    for path, text in files.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed files differ; write nothing")
    ap.add_argument("--root", type=Path, default=Path.cwd())
    args = ap.parse_args(argv)
    registry = load_registry(args.root)
    files = generate(registry)
    if args.check:
        committed = args.root / SOURCES_FILE
        if committed.is_file():
            check_raw_versions(committed.read_text(encoding="utf-8"), files[SOURCES_FILE])
        differ = stale(args.root, files)
        for p in differ:
            print(f"out of date: {p} (run make contracts)", file=sys.stderr)
        return 1 if differ else 0
    try:
        written = write(args.root, files)
    except (NotGenerated, RawContractChanged) as e:
        print(f"make contracts stopped: {e}", file=sys.stderr)
        return 1
    for p in written:
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
